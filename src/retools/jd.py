# -*- coding: utf-8 -*-
"""Безразмерная продуктивность и параметры трещины ГРП.

Порт VBA-функций модуля g__Misc.bas расчётника RE Tools (Get_Jd, Get_x_f) —
дословно, с сохранением коэффициентов и граничных условий оригинала.
"""
from __future__ import annotations

from math import exp, log


def get_jd(mu: float, b: float, k_h: float, h: float, j: float) -> float:
    """Безразмерный коэффициент продуктивности Jd (Get_Jd).

    Jd = 18.42 · µ · B · J / (k·h), где µ — сПз, B — м3/м3, k·h — мД·м,
    J — коэффициент продуктивности, м3/сут/атм.
    """
    khh = k_h * h
    if khh == 0:
        return 0.0
    return 18.42 * mu * b * j / khh


def get_x_f(r_w: float, k_h: float, s: float, w_f: float, k_f: float) -> float:
    """Полудлина трещины ГРП, эквивалентная заданному скин-фактору (Get_x_f).

    r_w — радиус скважины, м; k_h — проницаемость пласта, мД; s — скин-фактор;
    w_f — ширина трещины, мм→м в вызывающем коде; k_f — проницаемость проппанта, мД.
    Возвращает 0, если скин неотрицательный (не ГРП) или превышает предел.
    """
    if (w_f * k_f * k_h * r_w) == 0:
        return 0.0
    x_inf = w_f * k_f / 1.7 / k_h          # полудлина трещины бесконечной проводимости
    s_min = -log(x_inf / 2 / r_w)          # предельный отрицательный скин
    if s <= s_min:
        return 0.0                          # превышает предел
    if s < 0:
        return 2 * r_w * exp(-s) / (1 - 2 * r_w * exp(-s) / x_inf)
    return 0.0                              # не ГРП
